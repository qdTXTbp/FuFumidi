// ============================================================
// 场景光带（2026-10-17）—— "光影随透视角度变化"的唯一来源
//
// 用户实测：「音符的光影并没有随着透视角度变化」。上一版的明暗全写在音符自己的
// uv 空间里（相当于贴了一张贴图）：拖「键盘透视」只改变音符的形状，明暗条纹不动，
// 所以读起来是平的、假的。
//
// 这一版把它变成**相机相关**的量：
//   坡道上方有一条"棚灯"光带，它经坡道反射进相机的那一段深度，由**相机高度**决定。
//   相机越高压（= 键盘透视越大，H 越大、坡道越斜），反射点越往观众这边挪 ——
//   于是拖滑杆时，光带会沿着坡道扫过去。音符层按自己到光带的距离取亮度。
//
// 这里的 barS/barW 是坡道距离（像素，落点线以上为正），与 keyboard.js 的 s 同一单位。
// 纯函数，方便单测（见 tests/viz-primitives.test.js 的"光影随透视"）。
// ============================================================

/** 光带中心：persp=0 时落在坡道上部（0.82·sTop），拉到 1 时扫到下部（0.30·sTop） */
export function rampLight(sTop, persp) {
  const s = Math.max(0, Number(sTop) || 0);
  const ps = Math.max(0, Math.min(1, Number(persp) || 0));
  return { s: s * (0.82 - 0.52 * ps), w: Math.max(26, s * 0.17), ps };
}

/** 某条音符（坡道距离 sMid）被这条光带照到的强度：0..1 的高斯 */
export function lightAt(light, sMid) {
  if (!light || !(light.w > 0)) return 0;
  const d = ((Number(sMid) || 0) - light.s) / light.w;
  return Math.exp(-d * d);
}
