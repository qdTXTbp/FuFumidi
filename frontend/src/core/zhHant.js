/** 简体 → 繁体：先用「用词表」（按长度降序，长词优先以免被短词截断），再逐字转换。未收录汉字保持原样。 */
export function zhToHant(str) {
  if (!str) return str;
  let out = String(str);
  const phrases = Object.keys(PHRASE).sort((a, b) => b.length - a.length);
  for (const p of phrases) out = out.split(p).join(PHRASE[p]);
  for (const c in CHAR) out = out.split(c).join(CHAR[c]);
  return out;
}