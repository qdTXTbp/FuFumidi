/* 语言状态（响应式：切语言后 t() 返回值变化，Vue 模板自动重渲染） */
const langState = reactive({ lang: 'zh' }); // 'zh' | 'en'

export function setLang(v) { langState.lang = v === 'en' ? 'en' : 'zh'; }
export function getLang() { return langState.lang; }
export function isEn() { return langState.lang === 'en'; }

export function t(str) {
  if (langState.lang !== 'en') return str;
  return I18N_MAP[str] || str;
}
